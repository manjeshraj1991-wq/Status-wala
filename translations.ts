/**
 * Translate a UI key with fallback
 */
export function t(key: string, lang: Language): string {
  const currentLangDict = UI_TRANSLATIONS[lang];
  if (currentLangDict && currentLangDict[key]) {
    return currentLangDict[key];
  }
  // Fallback to Hindi or English
  if (UI_TRANSLATIONS.hi[key]) return UI_TRANSLATIONS.hi[key];
  return UI_TRANSLATIONS.en[key] || key;
}
